import type { SeedProduct, SeedVariant } from './catalog-generator.js';

export const r = (rupees: number) => Math.round(rupees * 100);

export function variant(
  sku: string,
  title: string,
  options: Record<string, string>,
  pricePaise: number,
  costRatio: number,
  stock: number,
  returnable = true,
): SeedVariant {
  return {
    sku,
    title,
    options,
    pricePaise,
    mrpPaise: Math.ceil((pricePaise * 1.12) / 100) * 100,
    costPricePaise: Math.round(pricePaise * costRatio),
    landedCost: {
      freight: Math.round(pricePaise * 0.012),
      paymentFee: Math.round(pricePaise * 0.02),
      expectedReturnCost: returnable ? Math.round(pricePaise * 0.008) : 0,
      nonRecoverableTax: 0,
    },
    minMarginBps: 800,
    stock,
    supplier: 'Demo Supplier Pvt Ltd',
    leadTimeDays: 5,
  };
}

